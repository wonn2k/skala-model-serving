    assert calendar_features("2025-05-03")[3] == 1.0  # 토 → 일 → 월(어린이날) → 화(대체) 연휴
    assert calendar_features("2025-05-17")[3] == 0.0  # 그냥 토요일 (토·일 2일)
    assert shift("2025-12-31", 1) == "2026-01-01"
